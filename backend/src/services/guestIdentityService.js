import {
  createHash,
  randomBytes,
  randomUUID,
} from 'node:crypto';

const sessionsByTokenHash = new Map();

export const GUEST_SESSION_TTL_MS = 12 * 60 * 60 * 1000;

const MIN_DISPLAY_NAME_LENGTH = 1;
const MAX_DISPLAY_NAME_LENGTH = 32;

function validateDisplayName(value) {
  if (typeof value !== 'string') {
    throw new TypeError('displayName must be a string.');
  }

  const displayName = value.trim();
  const characterCount = Array.from(displayName).length;

  if (
    characterCount < MIN_DISPLAY_NAME_LENGTH ||
    characterCount > MAX_DISPLAY_NAME_LENGTH
  ) {
    throw new TypeError(
      `displayName must contain ${MIN_DISPLAY_NAME_LENGTH}-${MAX_DISPLAY_NAME_LENGTH} characters.`,
    );
  }

  if (/[\u0000-\u001F\u007F]/u.test(displayName)) {
    throw new TypeError(
      'displayName must not contain control characters.',
    );
  }

  return displayName;
}

function hashSessionToken(token) {
  // Tokens generated by this service are exactly 43 base64url characters.
  // Reject malformed values before attempting a lookup.
  if (
    typeof token !== 'string' ||
    !/^[A-Za-z0-9_-]{43}$/.test(token)
  ) {
    return null;
  }

  return createHash('sha256')
    .update(token, 'utf8')
    .digest('hex');
}

function removeExpiredSessions(now = Date.now()) {
  for (const [tokenHash, session] of sessionsByTokenHash) {
    if (session.expiresAtMs <= now) {
      sessionsByTokenHash.delete(tokenHash);
    }
  }
}

/**
 * Creates a temporary guest identity and bearer session token.
 *
 * The raw token is returned to the caller once.
 * The in-memory session store keeps only its SHA-256 hash.
 */
export function createGuestIdentity({ displayName: inputName } = {}) {
  const displayName = validateDisplayName(inputName);
  const now = Date.now();

  removeExpiredSessions(now);

  const identity = {
    id: randomUUID(),
    displayName,
    createdAt: new Date(now).toISOString(),
  };

  const sessionToken = randomBytes(32).toString('base64url');
  const tokenHash = hashSessionToken(sessionToken);
  const expiresAtMs = now + GUEST_SESSION_TTL_MS;

  sessionsByTokenHash.set(tokenHash, {
    identity,
    expiresAtMs,
  });

  return {
    identity: { ...identity },
    sessionToken,
    expiresAt: new Date(expiresAtMs).toISOString(),
  };
}

/**
 * Resolves an identity from a valid, unexpired session token.
 * Returns null when the token is invalid, unknown, revoked, or expired.
 */
export function getGuestIdentityByToken(token) {
  const tokenHash = hashSessionToken(token);

  if (!tokenHash) {
    return null;
  }

  const session = sessionsByTokenHash.get(tokenHash);

  if (!session) {
    return null;
  }

  if (session.expiresAtMs <= Date.now()) {
    sessionsByTokenHash.delete(tokenHash);
    return null;
  }

  return { ...session.identity };
}

/**
 * Revokes a guest session.
 *
 * Returns true when an active session was removed; false otherwise.
 */
export function revokeGuestSession(token) {
  const tokenHash = hashSessionToken(token);

  if (!tokenHash) {
    return false;
  }

  return sessionsByTokenHash.delete(tokenHash);
}